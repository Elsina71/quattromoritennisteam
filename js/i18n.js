  const LOCALES = { it: 'it-IT', en: 'en-GB', es: 'es-ES' };
  const KEY = 'pcm-lang';

  function initial() {
    try {
      const saved = window.Consent ? Consent.read(KEY) : null;   // solo con il consenso alle preferenze
      if (saved && dict[saved]) return saved;
    } catch (e) { /* ignore */ }
    // il circolo è italiano: inglese o spagnolo solo per chi ha il browser in quella lingua
    const nl = (navigator.language || 'it').slice(0, 2);
    return nl === 'en' || nl === 'es' ? nl : 'it';
  }

  let lang = initial();

  return {
    get lang() { return lang; },
    set(l) {
      if (!dict[l]) return;
      lang = l;
      if (window.Consent) Consent.write(KEY, l);
    },
    locale() { return LOCALES[lang]; },
    t(key, params) {
      let s = (dict[lang] && dict[lang][key]) || dict.en[key] || key;
      if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? params[k] : m));
      return s;
    }
  };
